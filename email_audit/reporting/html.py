"""Self-contained HTML assessment report."""

from html import escape
import json
from urllib.parse import urlsplit

import markdown
from markdown.extensions import Extension
from markdown.treeprocessors import Treeprocessor

from email_audit.reporting.executive_summary import build_executive_summary


class _SafeLinks(Treeprocessor):
    def run(self, root):
        for element in root.iter():
            if element.tag == "a":
                try:
                    url = urlsplit(element.get("href", ""))
                    valid = url.scheme.lower() in {"http", "https"} and bool(url.netloc)
                except ValueError:
                    valid = False
                if not valid:
                    element.attrib.pop("href", None)
            elif element.tag == "img":
                element.tag = "span"
                element.text = element.get("alt", "")
                element.attrib.clear()


class _SafeLinksExtension(Extension):
    def extendMarkdown(self, md):
        md.treeprocessors.register(_SafeLinks(md), "safe_links", 0)


def _render_markdown(text):
    return markdown.markdown(
        escape(text, quote=False), extensions=["tables", _SafeLinksExtension()]
    )


def render_html(domain, commentary, recommendations, results, findings, auth_results=None,
                spoof_result=None):
    """Render a self-contained report with Markdown copy controls."""
    summary = build_executive_summary(domain, results, auth_results, spoof_result)
    cards = "\n".join(
        f'<div class="card"><span>{escape(result["control"])}</span>'
        f'<strong>{escape(result["assessment"])}</strong></div>'
        for result in results
    )
    sections = {
        "executive": ("Executive Summary", summary),
        "technical": ("Technical Commentary", commentary),
        "recommendations": ("Recommendations", recommendations),
    }
    markdown_data = {key: content for key, (_, content) in sections.items()}
    markdown_data["all"] = "\n\n".join(
        f"## {title}\n\n{content}" for title, content in sections.values()
    )
    safe_data = (
        json.dumps(markdown_data, ensure_ascii=False)
        .replace("&", "\\u0026")
        .replace("<", "\\u003c")
        .replace(">", "\\u003e")
        .replace("\u2028", "\\u2028")
        .replace("\u2029", "\\u2029")
    )

    def copy_controls(key, label):
        return (
            f'<div class="copy-controls"><button type="button" class="copy-button" '
            f'data-copy="{key}">{label}</button>'
            '<span class="copy-status" role="status" aria-live="polite"></span></div>'
        )

    narrative = "\n".join(
        f"<section><h2>{title}</h2>{copy_controls(key, 'Copy Markdown')}"
        f"{_render_markdown(content)}</section>"
        for key, (title, content) in sections.items()
    )
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>Email Audit Report - {escape(domain)}</title>
  <style>
    :root {{ color-scheme: light; font-family: system-ui, sans-serif; color: #172033; background: #f3f6fa; }}
    body {{ margin: 0; }}
    header {{ padding: 2rem max(1rem, calc((100% - 1100px) / 2)); background: #10233f; color: white; }}
    header h1 {{ margin: 0; }}
    main {{ max-width: 1100px; margin: 2rem auto; padding: 0 1rem; }}
    .cards {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(170px, 1fr)); gap: 1rem; }}
    .card, section {{ background: white; border: 1px solid #dce3ed; border-radius: .6rem; padding: 1rem; }}
    .card strong {{ display: block; margin-top: .35rem; }}
    section {{ margin: 1rem 0; line-height: 1.55; overflow-wrap: anywhere; }}
    table {{ border-collapse: collapse; width: 100%; }}
    th, td {{ border: 1px solid #dce3ed; padding: .5rem; text-align: left; }}
    .copy-controls {{ display: flex; align-items: center; gap: .75rem; margin: .75rem 0; }}
    .copy-button {{ padding: .45rem .7rem; border: 1px solid #9aa8bb; border-radius: .35rem; background: #f3f6fa; color: inherit; cursor: pointer; }}
    .copy-button:disabled {{ cursor: wait; opacity: .7; }}
    .copy-status {{ color: #53647b; font-size: .9rem; }}
    .copy-buffer {{ position: fixed; left: -9999px; top: 0; }}
    footer {{ color: #53647b; margin: 2rem 0; font-size: .9rem; }}
  </style>
</head>
<body>
  <header><h1>Email Audit Report</h1><p>{escape(domain)}</p></header>
  <main>
    <div class="cards" aria-label="Control assessments">{cards}</div>
    {copy_controls("all", "Copy All Markdown")}
    {narrative}
    <footer>Generated by Email Audit. This report works offline and loads no external resources.</footer>
  </main>
  <script id="markdown-data" type="application/json">{safe_data}</script>
  <script>
    const markdownData = JSON.parse(document.getElementById("markdown-data").textContent);
    async function copyMarkdown(text) {{
      if (navigator.clipboard?.writeText && window.isSecureContext) {{
        await navigator.clipboard.writeText(text);
        return;
      }}
      const buffer = document.createElement("textarea");
      buffer.value = text;
      buffer.className = "copy-buffer";
      document.body.append(buffer);
      buffer.select();
      let copied;
      try {{
        copied = document.execCommand("copy");
      }} finally {{
        buffer.remove();
      }}
      if (!copied) throw new Error("Clipboard access is unavailable.");
    }}
    for (const button of document.querySelectorAll(".copy-button")) {{
      button.addEventListener("click", async () => {{
        const status = button.nextElementSibling;
        button.disabled = true;
        status.textContent = "Copying...";
        try {{
          await copyMarkdown(markdownData[button.dataset.copy]);
          status.textContent = "Copied Markdown to clipboard.";
        }} catch {{
          status.textContent = "Copy failed. Select and copy the text manually.";
        }} finally {{
          button.disabled = false;
        }}
      }});
    }}
  </script>
</body>
</html>
"""


def export_html(domain, commentary, recommendations, results, findings, auth_results=None,
                spoof_result=None, filename=None):
    """Write the HTML report and return its path."""
    if filename is None:
        filename = f"{domain}.html"
    content = render_html(
        domain, commentary, recommendations, results, findings, auth_results, spoof_result
    )
    with open(filename, "w", encoding="utf-8") as handle:
        handle.write(content)
    return filename
